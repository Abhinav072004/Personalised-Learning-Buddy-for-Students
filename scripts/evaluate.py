"""Evaluation harness: run every student profile through the buddy and check
each plan against the evaluation checklist, then run the adaptation and
re-run-consistency experiments. Writes docs/evaluation_report.md.

    cd backend && python ../scripts/evaluate.py
"""
import os
import sys
import tempfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("DATABASE_URL", f"sqlite:///{Path(tempfile.gettempdir()) / 'buddy_eval.db'}")
os.environ["LLM_MODEL"] = ""

from sqlalchemy import select  # noqa: E402

from app.db import session_scope  # noqa: E402
from app.kb import load_kb  # noqa: E402
from app.models import Student  # noqa: E402
from app.seed import init_db  # noqa: E402
from app.services import compute, simulate  # noqa: E402

init_db(reset=True)
rows, fails, goals = [], Counter(), Counter()
adapt = []
with session_scope() as db:
    kb = load_kb(db)
    students = list(db.scalars(select(Student).order_by(Student.id)))
    for s in students:
        r1 = compute(db, s, kb=kb)
        r2 = compute(db, s, kb=kb)
        consistent = r1["plan"] == r2["plan"]
        v = r1["validation"]
        for c in v["checks"]:
            if not c["passed"] and c["severity"] == "error":
                fails[c["id"]] += 1
        goals[s.goal_id or "(vague)"] += 1
        p = r1["plan"]
        rows.append((s.id, s.programme, s.year, s.goal_id or "(vague)", v["passed"], consistent,
                     r1["diagnosis"]["readiness"], p.get("readiness_projected"), len(p["learning_track"]["skipped"]),
                     len(p["learning_track"]["deferred"])))
        reqs = kb.goal_requirements(s.goal_id or "", s.programme)
        if reqs:
            sk = reqs[0]["skill"]
            strong = simulate(db, s, [{"skill_id": sk, "source": "assessment", "score": 0.92, "attempts": 1, "time_spent_min": 10, "detail": "sim"}])
            weak = simulate(db, s, [{"skill_id": sk, "source": "assessment", "score": 0.2, "attempts": 3, "time_spent_min": 30, "detail": "sim"},
                                    {"skill_id": sk, "source": "exercise", "score": 0.0, "attempts": 3, "time_spent_min": 9, "detail": "sim"}])
            def hrs(res):
                return sum(it["hours"] for w in res["plan"]["learning_track"]["weeks"] for it in w["items"] if it.get("skill") == sk)
            adapt.append((s.id, sk, hrs(strong["after"]), hrs(weak["after"]),
                          any("Extra support" in c for c in weak["diff"]["changes"]),
                          strong["after"]["validation"]["passed"] and weak["after"]["validation"]["passed"]))

n = len(rows)
lines = ["# Evaluation report", "", "Generated by `python scripts/evaluate.py` (deterministic engine, no LLM).", "",
         "## 1. Plan validity across all profiles", "",
         f"- Profiles evaluated: **{n}** ({', '.join(f'{g}: {c}' for g, c in goals.most_common())})",
         f"- Plans passing every hard constraint check: **{sum(r[4] for r in rows)}/{n}**",
         f"- Identical plan on re-run (consistency): **{sum(r[5] for r in rows)}/{n}**",
         f"- Failed checks by type: {dict(fails) or 'none'}",
         f"- Mean goal readiness now -> projected: **{sum(r[6] or 0 for r in rows if r[6] is not None)/max(1,sum(1 for r in rows if r[6] is not None)):.0%} -> "
         f"{sum(r[7] or 0 for r in rows if r[7] is not None)/max(1,sum(1 for r in rows if r[7] is not None)):.0%}**",
         f"- Intro modules skipped because already known: {sum(r[8] for r in rows)}; items deferred for weekly time: {sum(r[9] for r in rows)}",
         "", "Checklist per plan: courses exist; offered that semester; prerequisites met; credit min/max; no repeats; backlogs at next offering;"
         " not-together pairs; rejected courses absent; open-elective slots; online-credit cap; minor eligibility; no mastered content;"
         " weekly hours; goal-skill coverage.", "",
         "## 2. Adaptation: strong vs weak mid-semester quiz on the top goal skill", "",
         f"- Profiles simulated: **{len(adapt)}**",
         f"- Weak result adds remedial support (refreshers / alternative explanations): **{sum(a[4] for a in adapt)}/{len(adapt)}**",
         f"- Weak result schedules at least as much time on that skill as strong: **{sum(a[3] >= a[2] for a in adapt)}/{len(adapt)}**",
         f"- Both adapted plans still valid: **{sum(a[5] for a in adapt)}/{len(adapt)}**",
         "- Where a weak result schedules *less* time on the skill itself, the time went to remedial prerequisite"
         " refreshers first and the skill's later modules were deferred to respect weekly hours (intended: prerequisites first).", "",
         "## 3. Per-profile results", "", "| Student | Prog | Year | Goal | Valid | Re-run same | Ready now | Projected | Skipped | Deferred |",
         "|---|---|---|---|---|---|---|---|---|---|"]
lines += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {'yes' if r[4] else 'NO'} | {'yes' if r[5] else 'NO'} | "
          f"{'' if r[6] is None else f'{r[6]:.0%}'} | {'' if r[7] is None else f'{r[7]:.0%}'} | {r[8]} | {r[9]} |" for r in rows]
(ROOT / "docs" / "evaluation_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines[:22]))
